import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs'
import { resolve } from 'node:path'
import process from 'node:process'
import ts from 'typescript'

const root = process.cwd()

// Every authored README in the monorepo (root + each package) plus the docs
// site content. Package READMEs are enumerated so a new package is covered
// automatically; the generated `api/` dirs are skipped inside markdownFiles().
const packagesDir = resolve(root, 'packages')
const packageReadmes = readdirSync(packagesDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => resolve(packagesDir, entry.name, 'README.md'))

// Scope: the curated copy-paste surface — the root README plus every package
// README. The docs-site MDX is deliberately excluded: it mixes react-live
// playground blocks and illustrative fragments (sibling JSX, partial code) that
// are not standalone modules, and its correctness is covered by the Docusaurus
// build plus react-live at runtime.
const inputs = [resolve(root, 'README.md'), ...packageReadmes].filter(existsSync)

function markdownFiles(path) {
  if (statSync(path).isFile()) return [path]
  return readdirSync(path, { withFileTypes: true }).flatMap((entry) => {
    if (entry.name === 'api') return [] // generated by TypeDoc
    const child = resolve(path, entry.name)
    return entry.isDirectory() ? markdownFiles(child) : /\.mdx?$/.test(entry.name) ? [child] : []
  })
}

const failures = []
const fencePattern = /^```(tsx|ts|jsx|js)([^\n]*)\n([\s\S]*?)^```\s*$/gm

for (const file of inputs.flatMap(markdownFiles)) {
  const source = readFileSync(file, 'utf8')
  for (const match of source.matchAll(fencePattern)) {
    const language = match[1]
    const info = match[2] ?? ''
    const code = match[3] ?? ''

    // `live` fences are react-live playground blocks: they render against the
    // ReactLiveScope (React, hooks, the components) injected at runtime, so they
    // are legitimately bare expressions/fragments that do not parse as a
    // standalone module. Checking them as modules is stricter than they are
    // meant to be. Static copy-paste snippets (no `live`) are still checked.
    if (/\blive\b/.test(info)) continue

    const before = source.slice(0, match.index)
    const line = before.split('\n').length + 1
    const relative = file.slice(root.length + 1)

    if (/^\s*;</m.test(code)) {
      failures.push(`${relative}:${String(line)} starts JSX with a stray leading semicolon`)
    }

    if (
      /\buseState\s*</.test(code) &&
      !/React\.useState\s*</.test(code) &&
      !/import\s*{[^}]*\buseState\b[^}]*}\s*from\s*['"]react['"]/.test(code)
    ) {
      failures.push(`${relative}:${String(line)} uses useState without importing it`)
    }

    const result = ts.transpileModule(code, {
      fileName: `snippet.${language}`,
      reportDiagnostics: true,
      compilerOptions: {
        target: ts.ScriptTarget.ES2022,
        module: ts.ModuleKind.ESNext,
        jsx: ts.JsxEmit.ReactJSX,
      },
    })

    for (const diagnostic of result.diagnostics ?? []) {
      if (diagnostic.category !== ts.DiagnosticCategory.Error) continue
      const message = ts.flattenDiagnosticMessageText(diagnostic.messageText, ' ')
      failures.push(`${relative}:${String(line)} does not parse: ${message}`)
    }
  }
}

if (failures.length > 0) {
  console.error(`Documentation snippet check failed:\n- ${failures.join('\n- ')}`)
  process.exit(1)
}

console.log('✔ Authored TypeScript/JavaScript snippets are clean')
